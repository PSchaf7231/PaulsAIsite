CREATE TABLE "PaxConversation" (
 "id" TEXT PRIMARY KEY, "data" JSONB NOT NULL, "leaseToken" TEXT, "leaseUntil" TIMESTAMP(3),
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, "updatedAt" TIMESTAMP(3) NOT NULL
);
CREATE TABLE "PaxLead" (
 "id" TEXT PRIMARY KEY, "conversationId" TEXT NOT NULL UNIQUE REFERENCES "PaxConversation"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "name" TEXT, "email" TEXT, "phone" TEXT, "source" TEXT NOT NULL DEFAULT 'WEBSITE', "stage" TEXT NOT NULL DEFAULT 'NEW_LEAD', "preferences" JSONB NOT NULL,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT "PaxLead_contact_required" CHECK ("email" IS NOT NULL OR "phone" IS NOT NULL)
);
CREATE TABLE "PaxAppointment" (
 "id" TEXT PRIMARY KEY, "leadId" TEXT NOT NULL REFERENCES "PaxLead"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "kind" TEXT NOT NULL, "preferredTime" TEXT NOT NULL, "status" TEXT NOT NULL DEFAULT 'REQUESTED', "confirmedAt" TIMESTAMP(3),
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "PaxSavedSearch" (
 "id" TEXT PRIMARY KEY, "leadId" TEXT NOT NULL REFERENCES "PaxLead"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "preferences" JSONB NOT NULL, "status" TEXT NOT NULL DEFAULT 'SAMPLE_ONLY', "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
